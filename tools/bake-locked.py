#!/usr/bin/env python3
"""Run the locked specs and write the body the wasm page exports.

The native project keeps a placeholder body. This file is the one
build.sh compiles into the module, so the page shows this build.
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = ROOT / "specs"
OUT = ROOT / "obj" / "gen" / "ai_amplifier-locked.adb"

TITLES = {
    "item_01.adb": "Repo skeleton",
    "item_02.adb": "Splash and live page",
    "item_03.adb": "Core tensor and maths",
    "item_04.adb": "Tiny trainable MLP",
    "item_05.adb": "Byte-level BPE and attention",
    "item_06.adb": "Contributor How-To and leaky ReLU",
    "item_07.adb": "SPARK proofs of the kernels",
    "item_08.adb": "Weight-space programming",
    "item_09.adb": "Recursive prompts",
    "item_10.adb": "Training-speed harness",
    "item_11.adb": "Wrong-turn traces",
    "item_12.adb": "Benchmark audit",
    "item_13.adb": "Reward-hacking demo",
    "item_14.adb": "Same model, different harness",
    "item_15.adb": "Checked steps",
    "item_17.adb": "Second checker",
    "item_18.adb": "Checking status",
}


def ada_string(text: str) -> str:
    if text == "":
        return '""'
    parts = []
    for line in text.splitlines(keepends=True):
        newline = line.endswith("\n")
        body = line[:-1] if newline else line
        literal = '"' + body.replace('"', '""') + '"'
        if newline:
            literal += " & ASCII.LF"
        parts.append(literal)
    return " &\n         ".join(parts)


def spans(lengths: list[int]) -> str:
    rows = []
    cursor = 1
    for length in lengths:
        rows.append(f"         ({cursor}, {length})")
        cursor += length
    return ",\n".join(rows)


def main() -> int:
    numbers = list(range(1, 16)) + [17, 18]
    files = [SPEC_DIR / f"item_{n:02d}.adb" for n in numbers]
    missing = [path.name for path in files if not path.is_file()]
    if missing:
        print("missing " + ", ".join(missing), file=sys.stderr)
        return 1
    names = []
    texts = []
    fingerprints = []
    statuses = []
    for path in files:
        title = TITLES[path.name]
        number = int(path.stem.split("_")[1])
        names.append(f"{number:02d}  {title}")
        texts.append(path.read_text(encoding="utf-8"))
        fingerprints.append(hashlib.sha256(path.read_bytes()).hexdigest())
        binary = ROOT / "bin" / path.stem
        if not binary.is_file():
            print(f"missing {binary}", file=sys.stderr)
            return 1
        ran = subprocess.run(
            [str(binary)],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        token = f"{path.stem.replace('_', ' ')} pass"
        # item_01 prints "item 01 pass"
        token = "item " + path.stem[-2:] + " pass"
        ok = ran.returncode == 0 and token in ran.stdout
        statuses.append("pass" if ok else "fail")
        if not ok:
            sys.stderr.write(ran.stdout)
            sys.stderr.write(ran.stderr)
            print(f"{path.name} did not pass", file=sys.stderr)
    passed = sum(1 for status in statuses if status == "pass")
    stat = (
        f"{passed} of {len(statuses)} statements passed in this build. "
        "A fingerprint stops a silent edit. "
        "It cannot tell whether a spec is the right one."
    )
    count = len(files)
    body = f"""--  Generated by tools/bake-locked.py. build.sh compiles this body
--  into the wasm module. The copy in src/ is the placeholder the
--  native project typechecks. Do not edit this file by hand.
package body AI_Amplifier.Locked
  with SPARK_Mode => Off
is

   Count_N : constant := {count};

   Item_No : constant array (1 .. Count_N) of Integer :=
      ({", ".join(str(n) for n in numbers)});

   type Span is record
      First  : Positive;
      Length : Natural;
   end record;

   type Span_List is array (1 .. Count_N) of Span;

   Name_Text : constant String :=
         {ada_string("".join(names))};
   Name_At : constant Span_List :=
       (
{spans([len(name) for name in names])}
       );

   Spec_Text : constant String :=
         {ada_string("".join(texts))};
   Spec_At : constant Span_List :=
       (
{spans([len(text) for text in texts])}
       );

   Fp_Text : constant String :=
         {ada_string("".join(fingerprints))};
   Fp_At : constant Span_List :=
       (
{spans([len(item) for item in fingerprints])}
       );

   Status_Text : constant String :=
         {ada_string("".join(statuses))};
   Status_At : constant Span_List :=
       (
{spans([len(item) for item in statuses])}
       );

   Stat_Text : constant String :=
         {ada_string(stat)};

   function In_Range (Index : Integer) return Boolean is
     (Index in 1 .. Count_N);

   function Count return Integer is (Count_N);

   function Item_Number (Index : Integer) return Integer is
   begin
      if not In_Range (Index) then
         return 0;
      end if;
      return Item_No (Index);
   end Item_Number;

   function Name_Length (Index : Integer) return Integer is
   begin
      if not In_Range (Index) then
         return 0;
      end if;
      return Name_At (Index).Length;
   end Name_Length;

   function Name_Byte (Index, Pos : Integer) return Integer is
   begin
      if not In_Range (Index) or else Pos < 1
        or else Pos > Name_At (Index).Length
      then
         return 0;
      end if;
      return Character'Pos (Name_Text (Name_At (Index).First + Pos - 1));
   end Name_Byte;

   function Text_Length (Index : Integer) return Integer is
   begin
      if not In_Range (Index) then
         return 0;
      end if;
      return Spec_At (Index).Length;
   end Text_Length;

   function Text_Byte (Index, Pos : Integer) return Integer is
   begin
      if not In_Range (Index) or else Pos < 1
        or else Pos > Spec_At (Index).Length
      then
         return 0;
      end if;
      return Character'Pos (Spec_Text (Spec_At (Index).First + Pos - 1));
   end Text_Byte;

   function Fingerprint_Length (Index : Integer) return Integer is
   begin
      if not In_Range (Index) then
         return 0;
      end if;
      return Fp_At (Index).Length;
   end Fingerprint_Length;

   function Fingerprint_Byte (Index, Pos : Integer) return Integer is
   begin
      if not In_Range (Index) or else Pos < 1
        or else Pos > Fp_At (Index).Length
      then
         return 0;
      end if;
      return Character'Pos (Fp_Text (Fp_At (Index).First + Pos - 1));
   end Fingerprint_Byte;

   function Status_Length (Index : Integer) return Integer is
   begin
      if not In_Range (Index) then
         return 0;
      end if;
      return Status_At (Index).Length;
   end Status_Length;

   function Status_Byte (Index, Pos : Integer) return Integer is
   begin
      if not In_Range (Index) or else Pos < 1
        or else Pos > Status_At (Index).Length
      then
         return 0;
      end if;
      return Character'Pos
        (Status_Text (Status_At (Index).First + Pos - 1));
   end Status_Byte;

   function Stat_Length return Integer is (Stat_Text'Length);

   function Stat_Byte (Index : Integer) return Integer is
   begin
      if Index < 1 or else Index > Stat_Text'Length then
         return 0;
      end if;
      return Character'Pos (Stat_Text (Index));
   end Stat_Byte;

end AI_Amplifier.Locked;
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT} ({passed} of {count} passed)")
    return 0 if passed == count else 1


if __name__ == "__main__":
    sys.exit(main())
